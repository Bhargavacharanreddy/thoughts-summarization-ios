import Foundation
import SwiftData

@MainActor
@Observable
class ThoughtsViewModel {
    var todaysThoughts: [Thought] = []
    var categories: [ThoughtCategory] = []
    var dailySummary: DailySummary?
    var historicalSummaries: [DailySummary] = []
    var todos: [TodoItem] = []

    var isCategorizingThoughts = false
    var isGeneratingSummary = false
    var generatingImageIDs: Set<UUID> = []
    var isGeneratingImage: Bool {
        dailySummary.map { generatingImageIDs.contains($0.id) } ?? false
    }
    var isSyncingHistory = false
    var isCleaningTranscript = false
    var isGeneratingTodos = false
    var errorMessage: String?
    /// Optional heading for the error dialog; falls back to a generic one.
    var errorTitle: String?

    private let modelContext: ModelContext
    let settings: AppSettings
    private var autoCategorizationTask: Task<Void, Never>?

    /// How many recent days History keeps summaries and images in sync for.
    private let historySyncDays = 7

    init(modelContext: ModelContext, settings: AppSettings) {
        self.modelContext = modelContext
        self.settings = settings
        loadTodaysData()
        loadTodos()
    }

    // MARK: - Adding Thoughts

    func addThought(_ content: String, inputType: InputType) {
        let trimmed = content.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else { return }
        let thought = Thought(content: trimmed, inputType: inputType)
        modelContext.insert(thought)
        todaysThoughts.insert(thought, at: 0)
        try? modelContext.save()
        scheduleAutoCategoriziation()
    }

    func deleteThought(_ thought: Thought) {
        todaysThoughts.removeAll { $0.id == thought.id }
        modelContext.delete(thought)
        try? modelContext.save()
    }

    func cleanAndAddVoiceThought(transcript: String, audioFileURL: URL?) async {
        let trimmed = transcript.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !trimmed.isEmpty else {
            if let url = audioFileURL { try? FileManager.default.removeItem(at: url) }
            return
        }

        isCleaningTranscript = true
        defer { isCleaningTranscript = false }

        var finalTranscript = trimmed

        if let service = settings.makeAIService() {
            if settings.selectedProvider == .openAI,
               let url = audioFileURL,
               let openAI = service as? OpenAIService {
                if let whisperText = try? await openAI.transcribeAudio(fileURL: url),
                   !whisperText.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    finalTranscript = whisperText
                }
            } else {
                if let cleaned = try? await service.cleanTranscript(trimmed),
                   !cleaned.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
                    finalTranscript = cleaned
                }
            }
        }

        if let url = audioFileURL { try? FileManager.default.removeItem(at: url) }
        addThought(finalTranscript, inputType: .voice)
    }

    // MARK: - AI: Categorize + Todos

    func categorize() async {
        guard let service = settings.makeAIService() else {
            errorMessage = settings.serviceUnavailableMessage
            return
        }
        guard !todaysThoughts.isEmpty else { return }

        isCategorizingThoughts = true
        defer { isCategorizingThoughts = false }

        let contents = todaysThoughts.map { $0.content }
        do {
            let results = try await service.categorize(thoughts: contents)
            updateCategories(from: results)
            // After categorizing, generate todos from the same thoughts
            await generateTodos(service: service, thoughts: contents)
        } catch {
            errorMessage = error.localizedDescription
        }
    }

    private func generateTodos(service: any AIService, thoughts: [String]) async {
        isGeneratingTodos = true
        defer { isGeneratingTodos = false }

        let categoryNames = categories.map { $0.name }
        do {
            let results = try await service.generateTodos(thoughts: thoughts, categories: categoryNames)
            guard !results.isEmpty else { return }

            // Each run sees all of today's thoughts, so its list replaces the previous run's
            // untouched tasks. Tasks the user edited or completed are kept.
            let today = Calendar.current.startOfDay(for: Date())
            let stale = todos.filter { $0.isAutoGenerated && !$0.isDone && $0.createdAt >= today }
            for item in stale { modelContext.delete(item) }
            todos.removeAll { item in stale.contains { $0.id == item.id } }

            var existingTitles = Set(todos.map { normalizedTitle($0.title) })
            for result in results {
                let key = normalizedTitle(result.title)
                guard !key.isEmpty, existingTitles.insert(key).inserted else { continue }
                let quadrant = EisenhowerQuadrant(rawValue: result.quadrant) ?? .notUrgentNotImportant
                let item = TodoItem(title: result.title, notes: result.notes, quadrant: quadrant)
                item.isAutoGenerated = true
                modelContext.insert(item)
                todos.append(item)
            }
            try? modelContext.save()
        } catch {
            // Todo generation is best-effort — don't surface this error to the user
        }
    }

    // MARK: - AI: Summary + Image

    func generateDailySummary() async {
        guard let service = settings.makeAIService() else {
            errorMessage = settings.serviceUnavailableMessage
            return
        }
        guard !todaysThoughts.isEmpty else { return }

        isGeneratingSummary = true
        defer { isGeneratingSummary = false }

        do {
            let today = Calendar.current.startOfDay(for: Date())
            let summary = try await upsertSummary(for: today, thoughts: todaysThoughts, existing: dailySummary, service: service)
            dailySummary = summary
            loadHistoricalSummaries()
            if canAutoGenerateImages {
                await generateImage(for: summary, service: service, reportErrors: false)
            }
        } catch {
            errorMessage = error.localizedDescription
        }
    }

    func generateImageForCurrentSummary() async {
        guard let summary = dailySummary else { return }
        await generateImage(for: summary)
    }

    func generateImage(for summary: DailySummary) async {
        guard let service = settings.makeAIService() else {
            errorMessage = settings.serviceUnavailableMessage
            return
        }
        await generateImage(for: summary, service: service)
    }

    /// OpenAI and Apple Intelligence (Image Playground) can make images; Claude can't, so automatic
    /// generation skips it instead of showing an error. Tapping Generate Image still reports it.
    private var canAutoGenerateImages: Bool {
        settings.selectedProvider != .claude
    }

    func isImageGenerating(for summary: DailySummary) -> Bool {
        generatingImageIDs.contains(summary.id)
    }

    /// Automatic generation passes `reportErrors: false` so a failed image never interrupts with an alert.
    private func generateImage(for summary: DailySummary, service: any AIService, reportErrors: Bool = true) async {
        guard !generatingImageIDs.contains(summary.id) else { return }
        generatingImageIDs.insert(summary.id)
        defer { generatingImageIDs.remove(summary.id) }

        do {
            if let imageData = try await service.generateSummaryImage(summary: summary.summaryText) {
                summary.imageData = imageData
                try? modelContext.save()
            }
        } catch {
            if reportErrors {
                errorTitle = "Couldn't Create Image"
                errorMessage = error.localizedDescription
            }
        }
    }

    /// Creates or refreshes the summary for `date` in place, clearing a stale image.
    private func upsertSummary(for date: Date, thoughts: [Thought], existing: DailySummary?, service: any AIService) async throws -> DailySummary {
        let text = try await service.dailySummary(thoughts: thoughts.map { $0.content })
        let summary: DailySummary
        if let existing {
            summary = existing
            summary.summaryText = text
            summary.thoughtCount = thoughts.count
            summary.imageData = nil
        } else {
            summary = DailySummary(date: date, summaryText: text, thoughtCount: thoughts.count)
            modelContext.insert(summary)
        }
        try? modelContext.save()
        return summary
    }

    func summarizeCategory(_ category: ThoughtCategory) async -> String? {
        guard let service = settings.makeAIService() else {
            errorMessage = settings.serviceUnavailableMessage
            return nil
        }
        let contents = category.thoughts.map { $0.content }
        guard !contents.isEmpty else { return nil }
        do {
            let text = try await service.summarize(thoughts: contents, forCategory: category.name)
            category.summary = text
            try? modelContext.save()
            return text
        } catch {
            errorMessage = error.localizedDescription
            return nil
        }
    }

    // MARK: - Todo CRUD

    func toggleTodoDone(_ todo: TodoItem) {
        todo.isDone.toggle()
        todo.isAutoGenerated = false
        try? modelContext.save()
    }

    func updateTodo(_ todo: TodoItem, title: String, notes: String, quadrant: EisenhowerQuadrant) {
        todo.title = title
        todo.notes = notes
        todo.quadrant = quadrant
        todo.isAutoGenerated = false
        try? modelContext.save()
    }

    private func normalizedTitle(_ title: String) -> String {
        title.lowercased()
            .components(separatedBy: CharacterSet.alphanumerics.inverted)
            .filter { !$0.isEmpty }
            .joined(separator: " ")
    }

    func deleteTodo(_ todo: TodoItem) {
        todos.removeAll { $0.id == todo.id }
        modelContext.delete(todo)
        try? modelContext.save()
    }

    func loadTodos() {
        let desc = FetchDescriptor<TodoItem>(
            sortBy: [SortDescriptor(\.createdAt, order: .reverse)]
        )
        todos = (try? modelContext.fetch(desc)) ?? []
    }

    // MARK: - History

    func loadHistoricalSummaries() {
        let desc = FetchDescriptor<DailySummary>(
            sortBy: [SortDescriptor(\.date, order: .reverse)]
        )
        historicalSummaries = (try? modelContext.fetch(desc)) ?? []
    }

    /// Brings recent days up to date: creates missing summaries, refreshes ones whose
    /// thoughts changed since they were generated, and fills in missing images.
    func syncHistory() async {
        guard !isSyncingHistory, let service = settings.makeAIService() else { return }
        isSyncingHistory = true
        defer { isSyncingHistory = false }

        let calendar = Calendar.current
        let today = calendar.startOfDay(for: Date())

        for offset in 0..<historySyncDays {
            guard let day = calendar.date(byAdding: .day, value: -offset, to: today) else { continue }
            let thoughts = loadThoughts(for: day)
            let existing = summary(for: day)

            var target = existing
            if !thoughts.isEmpty, existing == nil || existing?.thoughtCount != thoughts.count {
                do {
                    target = try await upsertSummary(for: day, thoughts: thoughts, existing: existing, service: service)
                    if offset == 0 { dailySummary = target }
                    loadHistoricalSummaries()
                } catch {
                    errorMessage = error.localizedDescription
                    return
                }
            }

            if canAutoGenerateImages, let target, target.imageData == nil {
                await generateImage(for: target, service: service, reportErrors: false)
            }
        }
    }

    private func summary(for date: Date) -> DailySummary? {
        let start = Calendar.current.startOfDay(for: date)
        let end = Calendar.current.date(byAdding: .day, value: 1, to: start)!
        let desc = FetchDescriptor<DailySummary>(
            predicate: #Predicate { $0.date >= start && $0.date < end }
        )
        return try? modelContext.fetch(desc).first
    }

    // MARK: - Clearing Data

    /// True while an AI task is writing data, when clearing could race with it.
    var isBusy: Bool {
        isSyncingHistory || isGeneratingSummary || isCategorizingThoughts
            || isGeneratingTodos || isCleaningTranscript || !generatingImageIDs.isEmpty
    }

    /// Deletes all summaries along with the thoughts and categories they were built from,
    /// so History has nothing to rebuild them from.
    func clearSummariesAndHistory() {
        autoCategorizationTask?.cancel()
        deleteAll(DailySummary.self)
        deleteAll(Thought.self)
        deleteAll(ThoughtCategory.self)
        try? modelContext.save()

        todaysThoughts = []
        categories = []
        dailySummary = nil
        historicalSummaries = []
    }

    func clearTasks() {
        deleteAll(TodoItem.self)
        try? modelContext.save()
        todos = []
    }

    func clearEverything() {
        clearSummariesAndHistory()
        clearTasks()
    }

    private func deleteAll<T: PersistentModel>(_ type: T.Type) {
        let items = (try? modelContext.fetch(FetchDescriptor<T>())) ?? []
        for item in items { modelContext.delete(item) }
    }

    func loadThoughts(for date: Date) -> [Thought] {
        let start = Calendar.current.startOfDay(for: date)
        let end = Calendar.current.date(byAdding: .day, value: 1, to: start)!
        let desc = FetchDescriptor<Thought>(
            predicate: #Predicate { $0.timestamp >= start && $0.timestamp < end },
            sortBy: [SortDescriptor(\.timestamp, order: .reverse)]
        )
        return (try? modelContext.fetch(desc)) ?? []
    }

    // MARK: - Private

    private func loadTodaysData() {
        let today = Calendar.current.startOfDay(for: Date())
        let tomorrow = Calendar.current.date(byAdding: .day, value: 1, to: today)!

        let thoughtDesc = FetchDescriptor<Thought>(
            predicate: #Predicate { $0.timestamp >= today && $0.timestamp < tomorrow },
            sortBy: [SortDescriptor(\.timestamp, order: .reverse)]
        )
        todaysThoughts = (try? modelContext.fetch(thoughtDesc)) ?? []

        let catDesc = FetchDescriptor<ThoughtCategory>(
            predicate: #Predicate { $0.date >= today && $0.date < tomorrow }
        )
        categories = (try? modelContext.fetch(catDesc)) ?? []

        let sumDesc = FetchDescriptor<DailySummary>(
            predicate: #Predicate { $0.date >= today && $0.date < tomorrow }
        )
        dailySummary = try? modelContext.fetch(sumDesc).first
    }

    private func updateCategories(from results: [CategoryResult]) {
        for cat in categories { modelContext.delete(cat) }
        categories = []

        for result in results {
            let cat = ThoughtCategory(name: result.name)
            for index in result.thoughtIndices {
                guard todaysThoughts.indices.contains(index) else { continue }
                let thought = todaysThoughts[index]
                thought.category = cat
                cat.thoughts.append(thought)
            }
            modelContext.insert(cat)
            categories.append(cat)
        }
        try? modelContext.save()
    }

    private func scheduleAutoCategoriziation() {
        autoCategorizationTask?.cancel()
        autoCategorizationTask = Task { @MainActor [weak self] in
            try? await Task.sleep(for: .seconds(4))
            guard let self, !Task.isCancelled else { return }
            // Background run: skip quietly if the provider isn't ready rather than alerting on every thought.
            guard self.settings.makeAIService() != nil else { return }
            await self.categorize()
        }
    }
}
